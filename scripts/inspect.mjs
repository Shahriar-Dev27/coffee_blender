import { chromium } from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('art/qa', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (msg) => { if (msg.type() === 'error') errors.push(msg.text().slice(0,300)); });
await page.goto('http://127.0.0.1:3100/', { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);
await page.screenshot({ path: 'art/qa/hero.png' });
console.log(JSON.stringify({ scene: await page.locator('html').getAttribute('data-scene'), errors, overflow: await page.evaluate(() => document.documentElement.scrollWidth > innerWidth) }));
await page.locator('#order').scrollIntoViewIfNeeded();
await page.waitForTimeout(900);
await page.screenshot({ path: 'art/qa/counter.png' });
await page.getByRole('button', { name: 'Add to order' }).click();
await page.getByRole('button', { name: 'Review order', exact: true }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: 'art/qa/drawer.png' });
await page.keyboard.press('Escape');
await page.setViewportSize({ width: 390, height: 844 });
await page.goto('http://127.0.0.1:3100/', { waitUntil: 'networkidle' });
await page.screenshot({ path: 'art/qa/mobile-hero.png' });
await page.locator('#order').scrollIntoViewIfNeeded();
await page.screenshot({ path: 'art/qa/mobile-counter.png' });
await browser.close();
